"""
Fade ложного пробоя уровня предыдущего дня (false breakout / stop-hunt fade).

ЗАЧЕМ ЭТОТ ЗАХОД ОТДЕЛЬНЫЙ И ЧЕМ ОН ВАЖЕН
------------------------------------------
Пять предыдущих заходов дали один и тот же ответ: трендследование на
крипто-мейджорах затухло, значимо, во всех вариантах — своих, чужих,
ансамблевых. Из этого следует проверяемое СЛЕДСТВИЕ, а не просто ещё одна
идея: если трендовое умирает потому, что пробои стали чаще проваливаться,
то ставка ПРОТИВ пробоя должна была не затухнуть, а окрепнуть.

Это первая гипотеза лаборатории, у которой ОЖИДАЕМОЕ НАПРАВЛЕНИЕ ЭФФЕКТА
ОБРАТНО всему проверенному раньше. Поэтому главный вопрос прогона не «есть ли
эдж», а «ведёт ли себя fade иначе, чем всё остальное»: не растёт ли он там,
где всё трендовое падает, и жив ли он в 2024–2026.

ПОЧЕМУ ЭТО НЕ «ЕЩЁ ОДИН MEAN-REVERSION»
---------------------------------------
Классический MR у нас мёртв: 24 гипотезы, в среднем 1.29 барьера из 7 —
худший класс в базе. Но он ставит на РАССТОЯНИЕ («цена далеко от средней —
вернётся»), а fade ставит на СОБЫТИЕ («цена сходила туда, где стоят стопы,
собрала их и не смогла там закрыться»). Разная природа сигнала, разная
частота, разный профиль стопа. Класс в базе всё равно помечен как
mean-reversion — честнее держать его в самом скептичном классе и смотреть,
отличается ли он от собратьев, чем завести ему отдельную уютную категорию.

⚠️ ГЛАВНОЕ ОГРАНИЧЕНИЕ ЭТОГО ПРОГОНА: НЕТ ОБЪЁМА
------------------------------------------------
Источники в один голос называют объём КЛЮЧЕВЫМ фильтром fade: ложный пробой
отличается от настоящего тем, что за ним не стоит поток (типичное правило —
не меньше четверти объёма бара должно приходиться на зону за уровнем).
В наших H4/D1 колонка volume ПУСТАЯ, поэтому проверяется ОСЛАБЛЕННАЯ версия:
только ценовое правило.

Отсюда прямое следствие для чтения результата: **отрицательный итог НЕ
закрывает идею fade**. Он закрывает ровно «fade без подтверждения объёмом».
Если ценовая часть окажется хотя бы нейтральной, это аргумент достать объём
и вернуться; если она глубоко отрицательна — объём вряд ли спасёт, но и
такой вывод надо формулировать с оговоркой.
"""

from __future__ import annotations

from ..engine.config import StrategyConfig, LEGACY_COSTS
from ..validation.hypothesis import Hypothesis
from .score import Idea

SRC = [
    "Wen/Bouri/Xu/Zhao, Intraday return predictability in the cryptocurrency "
    "markets: momentum, reversal, or both (SSRN 4080253)",
    "Arda, Bollinger Bands under Varying Market Regimes: breakout vs "
    "mean-reversion in BTC/USDT (SSRN 5775962)",
    "quantvps.com — Swing Failure Pattern: правила фиксации несостоявшегося "
    "пробоя (стоп за хвостом, R/R от 2:1)",
    "chartinglens.com / tradeslayers.com — liquidity sweep и fakeout: "
    "формализация «снял ликвидность и не удержался»",
]

VOLUME_CAVEAT = (
    "ОСЛАБЛЕННАЯ ВЕРСИЯ: источники называют фильтр объёма ключевым для fade "
    "(низкий объём за уровнем = пробой ложный), но в наших H4/D1 объёма нет. "
    "Проверяется только ценовое правило. Отрицательный результат закрывает "
    "«fade без объёма», а не идею fade целиком."
)

LOGIC = {
    "false_breakout_fade": (
        "За хаем и лоем предыдущего дня механически скапливаются стоп- и "
        "стоп-лосс-приказы: это самые публично известные уровни на графике. "
        "Заход цены за такой уровень исполняет их и создаёт поток, который "
        "НЕ является спросом или предложением по сути — он вынужденный. Если "
        "после исчерпания этого потока цена возвращается и закрывается "
        "обратно за уровнем, значит продолжающего движения за проколом не "
        "было. Ставка идёт на исчезновение вынужденного потока, а не на "
        "величину отклонения от средней."),
    "htf_trend": (
        "Направление старшего таймфрейма. Для fade источники называют его "
        "критичным по конкретной причине: прокол ПРОТИВ основного тренда — "
        "это чаще всего откат внутри тренда, который продолжится, а прокол "
        "ПО тренду — исчерпание контртрендовой попытки. Одинаковая ценовая "
        "фигура означает разное в зависимости от того, куда идёт рынок "
        "этажом выше. Информация с другого горизонта, а не второй взгляд на "
        "те же бары."),
}

# фактор старшего ТФ: на H4 шесть баров = сутки; на D1 семь баров = неделя
HTF_FACTOR = {"4h": 6, "1d": 7}


def _idea(rationale: str, comps: list[str]) -> Idea:
    return Idea(rationale=rationale + " " + VOLUME_CAVEAT,
                sources=list(SRC), cross_market=True,
                component_logic={c: LOGIC[c] for c in comps})


def _cfg(name, exit_, filters, tf) -> StrategyConfig:
    return StrategyConfig.from_dict({
        "name": f"{name}_{tf}", "direction": "both", "timeframe": tf,
        "entry": {"type": "false_breakout_fade",
                  "params": {"stop_buffer": 0.0005}},
        # стоп ЗА ХВОСТОМ ложного пробоя приходит из самой заявки
        "stop": {"type": "block", "params": {}},
        "exit": exit_, "filters": filters,
        "sizing": {"risk_pct": 0.01}, "costs": dict(LEGACY_COSTS),
        "meta": {"source": "; ".join(SRC), "caveat": VOLUME_CAVEAT},
    })


def _h(cfg, grid, idea) -> tuple[Hypothesis, Idea]:
    return (Hypothesis(cfg, grid=grid, source="веб-поиск: false breakout fade",
                       notes=idea.rationale, grid_cap=40), idea)


def fade_pool(tf: str = "1d") -> list[tuple[Hypothesis, Idea]]:
    """Четыре гипотезы: {фикс R/R, возврат к противоположной границе} ×
    {без фильтра, с трендом старшего ТФ}.

    Ширина сознательно минимальная. Вопрос прогона — «ведёт ли себя fade
    иначе», и на него отвечает разбивка по годам, а не количество вариантов.
    Каждая лишняя гипотеза поднимает планку барьера 5 всем будущим кандидатам,
    и платить этим за перебор ради перебора здесь незачем.
    """
    factor = HTF_FACTOR.get(tf, 6)
    # предохранитель по времени: fade — ставка на быстрый возврат. Если через
    # max_bars возврата нет, тезис сделки не подтвердился, и держать её значит
    # превращать fade в что-то другое.
    max_bars = 10 if tf == "1d" else 30

    RR_EXIT = {"type": "fixed_rr", "params": {"rr": 2.0, "max_bars": max_bars}}
    OPP_EXIT = {"type": "level_target", "params": {"max_bars": max_bars}}
    HTF = [{"type": "htf_trend", "params": {"factor": factor, "ema_period": 50}}]

    RR_GRID = {"exit.params.rr": [1.5, 2.0, 2.5],
               "entry.params.stop_buffer": [0.0005, 0.002]}
    OPP_GRID = {"entry.params.stop_buffer": [0.0005, 0.002, 0.005],
                "exit.params.max_bars": [max_bars // 2, max_bars, max_bars * 2]}

    base = ("Ложный пробой уровня предыдущего дня: цена сходила за уровень, "
            "где стоят стопы, и не смогла там закрыться. Ставка на то, что "
            "поток, создавший прокол, был вынужденным и закончился. ")

    P = []
    P.append(_h(_cfg("fade_fbf_rr", dict(RR_EXIT), [], tf), dict(RR_GRID),
                _idea(base + "Выход по фиксированному R/R — версия, которую "
                             "описывают источники (2:1 и лучше).",
                      ["false_breakout_fade"])))

    P.append(_h(_cfg("fade_fbf_opposite", dict(OPP_EXIT), [], tf), dict(OPP_GRID),
                _idea(base + "Выход у ПРОТИВОПОЛОЖНОЙ границы вчерашнего дня: "
                             "цель не абстрактное кратное риску, а конкретный "
                             "уровень, до которого доходит возврат, если "
                             "прокол был ложным. Проверяет, не задаёт ли "
                             "фиксированный R/R цель, которой в структуре "
                             "рынка не соответствует ничего.",
                      ["false_breakout_fade"])))

    P.append(_h(_cfg("fade_fbf_rr_htf", dict(RR_EXIT), list(HTF), tf),
                {"exit.params.rr": [1.5, 2.0, 2.5],
                 "filters.0.params.ema_period": [30, 50, 100]},
                _idea(base + "Плюс фильтр старшего тренда: fade берётся только "
                             "в сторону тренда этажом выше. Источники называют "
                             "этот фильтр критичным.",
                      ["false_breakout_fade", "htf_trend"])))

    P.append(_h(_cfg("fade_fbf_opposite_htf", dict(OPP_EXIT), list(HTF), tf),
                {"entry.params.stop_buffer": [0.0005, 0.002, 0.005],
                 "filters.0.params.ema_period": [30, 50, 100]},
                _idea(base + "Возврат к противоположной границе плюс фильтр "
                             "старшего тренда — полная версия, которую "
                             "описывают источники.",
                      ["false_breakout_fade", "htf_trend"])))
    return P
