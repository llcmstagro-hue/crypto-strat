def _idea(rationale: str, comps: list[str]) -> Idea:
    return Idea(rationale=rationale, sources=list(SRC), cross_market=True,
                component_logic={c: LOGIC[c] for c in comps})


def _h(cfg: StrategyConfig, grid: dict, idea: Idea) -> tuple[Hypothesis, Idea]:
    return (Hypothesis(cfg, grid=grid, source="внешний источник: Куртни Смит",
                       notes=idea.rationale, grid_cap=40), idea)


def _cfg(name, entry, stop, exit_, filters, tf, risk=0.01) -> StrategyConfig:
    return StrategyConfig.from_dict({
        "name": f"{name}_{tf}", "direction": "both", "timeframe": tf,
        "entry": entry, "stop": stop, "exit": exit_, "filters": filters,
        "sizing": {"risk_pct": risk}, "costs": dict(LEGACY_COSTS),
        "meta": {"source": "; ".join(SRC), "external": "Courtney Smith"},
    })


ADX_FILTER = {"type": "adx_rising", "params": {"period": 14}}


# --------------------------------------------------------------------------- #
def smith_pool(tf: str = "1d") -> list[tuple[Hypothesis, Idea]]:
    P: list[tuple[Hypothesis, Idea]] = []

    # ---------------------------------------------------------------- #
    # ГЛАВА 3. ПРОРЫВЫ КАНАЛА
    # Вход: стоп-приказ чуть выше N-дневного максимума / ниже минимума.
    # Начальный стоп И выход: приказ с ДРУГОЙ стороны M-дневного канала —
    # у Смита это физически один и тот же приказ («пусть исходный приказ на
    # продажу остаётся у вашего брокера»).
    # ---------------------------------------------------------------- #
    def _channel(name, entry_p, exit_p, extra_filters=(), exit_kind="channel",
                 grid=None, note=""):
        entry = {"type": "channel_stop", "params": {"period": entry_p,
                                                    "buffer": 0.0002}}
        stop = {"type": "channel", "params": {"period": exit_p}}
        if exit_kind == "channel":
            ex = {"type": "channel", "params": {"period": exit_p}}
        elif exit_kind == "cutoff":
            entry["params"]["cutoff"] = True
            entry["params"]["flat_days"] = 5
            ex = {"type": "channel", "params": {"period": exit_p, "cutoff": True}}
        else:                                    # bishop
            ex = {"type": "bishop", "params": {"adx_period": 14, "adx_level": 40.0}}
        comps = ["channel_stop"] + (["adx_rising"] if extra_filters else [])
        return _h(_cfg(name, entry, stop, ex, list(extra_filters), tf),
                  grid or {"entry.params.period": [entry_p - 5, entry_p, entry_p + 5]},
                  _idea(note, comps))

    P.append(_channel(
        "smith_channel_20_20", 20, 20,
        note=("Классический прорыв канала 20/20 из гл. 3: вход стоп-приказом за "
              "20-дневный экстремум, выход и начальный стоп — приказ с "
              "противоположной стороны того же канала. Базовая форма метода, "
              "относительно которой автор строит все свои усовершенствования.")))

    P.append(_channel(
        "smith_channel_40_20", 40, 20,
        grid={"entry.params.period": [30, 40, 50]},
        note=("Асимметричный вариант: вход по редкому 40-дневному прорыву, а "
              "выход по более чуткому 20-дневному каналу. Смысл асимметрии — "
              "входить только в по-настоящему сильные движения, но не отдавать "
              "рынку всю прибыль на откате.")))

