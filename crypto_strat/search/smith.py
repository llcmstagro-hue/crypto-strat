"""
Внешний источник: Куртни Смит, «Как стабильно зарабатывать на рынке FOREX».
ВСЕ бэктестируемые методы книги, кроме Conqueror (гл. 4) — он прогнан отдельно.

Зачем это отдельный прогон, а не «ещё одна пачка гипотез». Все предыдущие
прогоны показали одно и то же: трендовые механизмы на крипто-мейджорах
затухли между 2017–21 и 2022–26, и затухли значимо. Возражение к этому выводу
всегда одно и то же — «вы проверяли СВОИ формализации, а не настоящие методы».
Книга Смита закрывает именно это возражение: правила придуманы не нами, до
крипты, под другой рынок, и извлечены из первоисточника, а не из чужого
скрипта. Если и они затухают — вывод перестаёт быть свойством нашего кода.

ЧТО ВЗЯТО И ЧЕГО СОЗНАТЕЛЬНО НЕТ
--------------------------------
Взято всё, что автор описывает МЕХАНИЧЕСКИ:
  гл. 2 — анализ тренда по свингам Демарка, фильтр ADX, выход Bishop;
  гл. 3 — прорывы канала 20/20, 40/20, 55/20 и правило отсечения;
  гл. 5 — стохастик: %K пересекает 50, всегда в рынке;
  гл. 6 — внутренние дни, дни разворота;
  гл. 8 — Slingshot и Mini-Slingshot.

НЕ взято то, что автор описывает дискреционно, — и это не лень, а честность:
  * торговля дивергенций стохастика (гл. 5). Автор прямо говорит, что входит
    «по любому предлогу» и «с минимальным подтверждением или даже без
    такового». Любая формализация здесь была бы НАШЕЙ стратегией с чужим
    названием, и её результат ничего не говорил бы о методе Смита;
  * частичные фиксации прибыли (половина позиции на цели, ещё половина на
    двойной цели и т.д.). Движок ведёт одну неделимую позицию — это следствие
    правил CFT, а не упрощение. Для Slingshot автор САМ предлагает
    альтернативный выход одним куском (Bishop), его и используем;
  * управление размером позиции «докупить, если рынок пойдёт дальше» — то же
    ограничение.

Сетки НАМЕРЕННО узкие. Это проверка чужого метода с авторскими параметрами, а
не поиск удачной его версии: широкий перебор превратил бы «работает ли метод
Смита» в «найдётся ли настройка метода Смита, которая красиво лежит на этой
истории». Evolution к этому классу не применяется по той же причине.
"""

